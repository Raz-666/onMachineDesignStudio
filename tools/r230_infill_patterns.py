"""R230 (.136ab): the COMPLETE infill pattern list.

User ask (.136aa round): 'the infill patterns are only about having a
COMPLETE list of all patterns - it simply makes recognizing internal
infill easier in our multi-stage recognition system.' The family
document (uploads/slicer-families.md ch. 'Alle Infill-Muster') lists
every pattern of every family; the recognition stack (L1 map/ladder,
L3 geometry classifier, L4 CUSTOM watch) should never leave a NAMED
pattern to CUSTOM.

F1  every sparse pattern of every family resolves to INFILL-SPARSE -
    34 spellings: Prusa/Orca/Bambu (rectilinear, aligned rectilinear,
    grid, triangles, stars, tri-hexagon, cubic, adaptive cubic,
    support cubic, quarter cubic, line, concentric, honeycomb,
    3d honeycomb, gyroid, hilbert curve, archimedean chords, octagram
    spiral, lightning, zig zag, cross zag, locked zag, cross hatch,
    tpms, tpms-d, tpms-fk, lateral honeycomb, lattice, spiral inset),
    Cura (cubic subdivision, octet, cross, cross 3d), Simplify3D
    (fast honeycomb).
F2  the top/bottom pattern family (monotonic, monotonic lines) is
    SOLID fill - smooth-surface patterns, the INFILL-SOLID class.
F3  'support cubic' is SPARSE infill (Prusa's variant that props the
    top surfaces) - the EXACT key beats the support substring; real
    support spellings stay SUPPORT (regression).
F4  end to end: a file that tags its infill by pattern name
    (';TYPE:Gyroid') gets clean INFILL-SPARSE feature blocks - no
    CUSTOM, the overrides menu can tune it.
F5  prose around patterns never becomes a feature boundary.

Run: python3 tools/r230_infill_patterns.py   (exit 0 = all green)
"""
import os
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import r2_postproc as pp                                  # noqa: E402

fails = []
N = 0


def check(name, ok, info=''):
    global N
    N += 1
    if not ok:
        fails.append(name)
        print('  FAIL %s %s' % (name, str(info)[:240]))
    else:
        print('  ok   %s' % name)


SPARSE = [
    'Rectilinear', 'Aligned Rectilinear', 'Grid', 'Triangles', 'Stars',
    'Tri-Hexagon', 'Cubic', 'Adaptive Cubic', 'Support Cubic',
    'Quarter Cubic', 'Line', 'Lines', 'Concentric', 'Honeycomb',
    '3D Honeycomb', 'Gyroid', 'Hilbert Curve', 'Archimedean Chords',
    'Octagram Spiral', 'Lightning', 'Zig Zag', 'Cross Zag', 'Locked Zag',
    'Cross Hatch', 'TPMS', 'TPMS-D', 'TPMS-FK', 'Lateral Honeycomb',
    'Lattice', 'Spiral Inset', 'Cubic Subdivision', 'Octet', 'Cross',
    'Cross 3D', 'Fast Honeycomb',
]
SOLID = ['Monotonic', 'Monotonic Lines']

print('--- F1: every sparse pattern of every family -> INFILL-SPARSE')
for _p in SPARSE:
    check('F1 ;TYPE:%-20s -> INFILL-SPARSE' % _p,
          pp._canon_type(_p) == 'INFILL-SPARSE', pp._canon_type(_p))

print('--- F2: top/bottom patterns -> INFILL-SOLID')
for _p in SOLID:
    check('F2 ;TYPE:%-20s -> INFILL-SOLID' % _p,
          pp._canon_type(_p) == 'INFILL-SOLID', pp._canon_type(_p))

print('--- F3: support cubic is infill; real support stays support')
check('F3 support cubic = SPARSE infill (exact key beats the substring)',
      pp._canon_type('Support Cubic') == 'INFILL-SPARSE')
check('F3 support spellings unchanged (regression)',
      all(pp._canon_type(s) == 'SUPPORT' for s in
          ('support', 'tree support', 'support interface', 'dense support',
           'support roof', 'painted support')))

print('--- F4: end to end - pattern names tag clean feature blocks')
D = tempfile.mkdtemp(prefix='r230_')
p4 = os.path.join(D, 'patterned.gcode')
open(p4, 'w').write('\n'.join([
    '; generated by OrcaSlicer 2.4.0', 'M82', 'G90', 'G28',
    'G0 X50 Y50 Z0.2 F3000',
    ';TYPE:Outer wall',
    'G1 X150 Y50 E1 F1800', 'G1 X150 Y150 E2', 'G1 X50 Y150 E3',
    ';TYPE:Gyroid',
    'G1 X60 Y60 E4', 'G1 X140 Y140 E5',
    ';TYPE:Monotonic',
    'G1 X60 Y140 E6', 'G1 X140 Y60 E7',
    'PRINT_END']) + '\n')
pp.process(p4)
_t4 = open(p4).read()
check('F4 gyroid block -> APPLY_TYPE TYPE=INFILL-SPARSE (tunable, not '
      'CUSTOM)',
      'APPLY_TYPE TYPE=INFILL-SPARSE' in _t4
      and 'APPLY_TYPE TYPE=CUSTOM' not in _t4,
      [_l for _l in _t4.split('\n') if 'APPLY_TYPE' in _l])
check('F4 monotonic block -> APPLY_TYPE TYPE=INFILL-SOLID',
      'APPLY_TYPE TYPE=INFILL-SOLID' in _t4)
check('F4 wall block survives around the patterns (regression)',
      'APPLY_TYPE TYPE=WALL-OUTER' in _t4)

print('--- F5: prose around patterns stays inert')
for _ln in ('; infill pattern = gyroid', '; grid is nice today',
            '; total infill lines: 42', ';LAYER:3'):
    check('F5 prose inert: %s' % _ln, pp.TYPE_RE.match(_ln) is None)

import shutil
shutil.rmtree(D, ignore_errors=True)

print()
if fails:
    print('R230 INFILL PATTERNS: %d checks, %d FAIL' % (N, len(fails)))
    for f in fails:
        print('  -', f)
    sys.exit(1)
print('R230 INFILL PATTERNS: %d checks, 0 FAIL - the pattern list is '
      'complete' % N)
