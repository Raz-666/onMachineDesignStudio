"""R226 (.136x): regression pins for the .136w field log round.

  B1  SMART_PARK crash: OrcaSlicer/Bambu write EXCLUDE_OBJECT_DEFINE with
      CENTER only. KAMP's SMART_PARK runs objects | map(attribute='polygon')
      -> jinja UndefinedError -> the print start ABORTS (field log: three
      SMART_PARK errors at 11:26 + 11:30, printer in ERROR state, no print).
      Fix 1: the watcher MEASURES the object outline from its moves and
      appends POLYGON= to CENTER-only defines (_upgrade_center_excludes).
  B2  our own placement macros (_PRIME_LINE, _PARK_HEAD, _PURGE_STRIP)
      read o.polygon too - all three tolerate CENTER-only objects now
      (20x20mm box around the center; renders pinned in macro_render_test).
  B3  the KAMP call sites are guarded: SMART_PARK is skipped with a hint
      when any object lacks a polygon, the adaptive mesh degrades to a
      full bed via KAMP's renamed native command.
  B4  gen_busy zombie: the flag lives in variables.cfg and SURVIVES klippy
      restarts; the R223 boot-drop only ran when the WATCHER restarted,
      and a release could fail while klippy was down (the finally pushed
      into a refusing moonraker). Every scan pass now RECONCILES the flag
      with reality - no thread, no queue -> clear, loudly.
  B5  klippy.log in the web console: the R216 filter expected per-line
      timestamps - klippy.log HAS NONE (the 12 MB field log: 0 of 237k
      lines) -> the export was EMPTY (512 bytes, header only - the field
      report's klippy-day.txt). Sections per klippy restart now: window
      picks sections by 'Start printer at', config dumps are skipped, the
      current run always stays, an empty result falls back to the raw tail.

Run: python3 tools/r226_field_fixes.py   (exit 0 = all green)
"""
import importlib.util
import os
import re
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import r2_postproc as pp                                  # noqa: E402

fails = []
N = 0


def check(name, ok, info=''):
    global N
    N += 1
    if not ok:
        fails.append(name)
        print('  FAIL %s %s' % (name, str(info)[:240]))
    else:
        print('  ok   %s' % name)


D = tempfile.mkdtemp(prefix='r226_')

# ===================================================== B1: polygon upgrade ==
print('--- B1: CENTER-only defines get a measured POLYGON')
p1 = os.path.join(D, 'vase.gcode')
open(p1, 'w').write('\n'.join([
    '; generated by OrcaSlicer 2.4.0', 'M82', 'G90',
    # the EXACT field line (vasev650.stl_id_0_copy_0, CENTER only)
    'EXCLUDE_OBJECT_DEFINE NAME=vasev650.stl_id_0_copy_0 '
    'CENTER=109.932,107.039',
    'PRINT_START', 'G0 X90 Y80 Z0.2 F3000',
    'G1 X130 Y80 E1 F1800', 'G1 X130 Y140 E2',
    'G1 X90 Y140 E3', 'G1 X90 Y80 E4', 'PRINT_END']) + '\n')
check('B1 single object: upgraded with the measured global bbox '
      '(exactly the field file line)',
      pp._upgrade_center_excludes(p1)
      and 'EXCLUDE_OBJECT_DEFINE NAME=vasev650.stl_id_0_copy_0 '
          'CENTER=109.932,107.039 '
          'POLYGON=[[90.00,80.00],[130.00,80.00],[130.00,140.00],'
          '[90.00,140.00]]' in open(p1).read(), open(p1).read()[:200])
check('B1 idempotent: a second pass changes nothing',
      pp._upgrade_center_excludes(p1) is False
      and open(p1).read().count('POLYGON=') == 1)
p2 = os.path.join(D, 'two.gcode')
open(p2, 'w').write('\n'.join([
    'M82', 'G90',
    'EXCLUDE_OBJECT_DEFINE NAME=a CENTER=50,50',
    'EXCLUDE_OBJECT_DEFINE NAME=b CENTER=150,50',
    'G0 X40 Y40 Z0.2 F3000',
    'EXCLUDE_OBJECT_START NAME=a',
    'G1 X60 Y40 E1', 'G1 X60 Y60 E2', 'G1 X40 Y60 E3',
    'EXCLUDE_OBJECT_END',
    # a real slicer TRAVELS (no E) between objects - without this line
    # the first extruding chord of b starts at a's last point and the
    # chord-covering attribution (start point counts too, by design)
    # would rightly stretch b's bbox over the whole file
    'G0 X140 Y40',
    'EXCLUDE_OBJECT_START NAME=b',
    'G1 X160 Y40 E4',
    'EXCLUDE_OBJECT_END', 'PRINT_END']) + '\n')
pp._upgrade_center_excludes(p2)
_t2 = open(p2).read()
check('B1 two objects WITH spans: each gets its OWN bbox '
      '(a: 40..60, b: 140..160)',
      'NAME=a CENTER=50,50 POLYGON=[[40.00,40.00],[60.00,40.00],'
      '[60.00,60.00],[40.00,60.00]]' in _t2
      and 'NAME=b CENTER=150,50 POLYGON=[[140.00,40.00],[160.00,40.00],'
          '[160.00,40.00],[140.00,40.00]]' in _t2, '')
p3 = os.path.join(D, 'unmeasurable.gcode')
open(p3, 'w').write('M82\nEXCLUDE_OBJECT_DEFINE NAME=x CENTER=1,2\n'
                    'PRINT_END\n')
check('B1 unmeasurable (no moves): the line stays CENTER-only '
      '(no invented data)',
      pp._upgrade_center_excludes(p3) is False
      and 'POLYGON' not in open(p3).read())
p4 = os.path.join(D, 'cura_style.gcode')
open(p4, 'w').write(
    'EXCLUDE_OBJECT_DEFINE NAME=d POLYGON=[[1,2],[3,2],[3,4],[1,4]]\n'
    'G1 X1 Y1 E1\n')
check('B1 POLYGON already present: early exit, file untouched',
      pp._upgrade_center_excludes(p4) is False)
_src = open(os.path.join(REPO, 'tools', 'r2_postproc.py')).read()
check('B1 watcher integration: the scan calls the upgrader for every '
      'changed file (seen-key cache)',
      '_upgrade_center_excludes(p)' in _src
      and 'eod_upgraded' in _src)

# ================================================ B2/B3: macro tolerances ==
print('--- B2/B3: macro code (renders live in macro_render_test R226)')
_m08 = open(os.path.join(REPO, 'macros', '08_print_start_stop.cfg')).read()
_m09 = open(os.path.join(REPO, 'macros', '09_pause_filament.cfg')).read()
_m14 = open(os.path.join(REPO, 'macros', '14_kamp.cfg')).read()
check('B2 _PRIME_LINE/_PARK_HEAD/_PURGE_STRIP: o.polygon guarded '
      '(is defined + 20x20mm center box fallback)',
      _m08.count("o.polygon is defined") == 1
      and _m09.count("o.polygon is defined") == 2
      and _m08.count('o.center[0]-10') == 2
      and _m09.count('o.center[0]-10') == 4)
check('B3 SMART_PARK call guarded: skipped with a hint when any object '
      'lacks a polygon',
      "selectattr('polygon', 'defined')" in _m08
      and 'KAMP Smart Park skipped: object defined with CENTER only'
      in _m08)
check('B3 adaptive mesh degrades: KAMP path only with polygons, else '
      'full bed via the renamed native command + hint',
      "selectattr('polygon', 'defined')" in _m14
      and '_BED_MESH_CALIBRATE PROFILE={profile}' in _m14
      and 'KAMP adaptive mesh skipped' in _m14)

# ================================================ B4: gen_busy reconcile ==
print('--- B4: gen_busy reconciliation in the scan loop')
check('B4 every scan pass compares the flag with reality '
      '(no thread, no queue -> clear, loudly)',
      'stale gen_busy cleared' in _src
      # R227: 7 = 6 releases + the new SILENT retry (a refusing klippy
      # must not spray the console - see r227_reconcile_fix F2)
      and _src.count("SAVE_VARIABLE VARIABLE=gen_busy VALUE=0") == 8  # R281: the held-scan clear
      # the race guard: the queue worker raises _JOB_STATE['busy']
      # BEFORE the flag - the reconciliation must check both
      and 'not _JOB_STATE.get(\'busy\')' in _src)

# ================================================ B5: klippy.log sections ==
print('--- B5: klippy.log export - the REAL file format')
spec = importlib.util.spec_from_file_location(
    'r2m', os.path.join(REPO, 'web', 'r2_menu.py'))
r2m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(r2m)
comp = r2m.R2MenuComponent.__new__(r2m.R2MenuComponent)

# a synthetic log in the real section format (asctime markers, dumps)
_lg = os.path.join(D, 'klippy.log')
import datetime as _dt
_now = _dt.datetime.now()
_old = _now - _dt.timedelta(hours=20)
open(_lg, 'w').write(
    '===== Config file =====\n[virtual_sdcard]\nOLD HEAD DUMP\n'
    '=======================\nold runtime 0\n'
    'Start printer at %s\n'
    '===== Config file =====\n[virtual_sdcard]\nOLD SECTION DUMP\n'
    '=======================\nold runtime 1\n'
    'Start printer at %s\n'
    '===== Config file =====\n[virtual_sdcard]\nFRESH DUMP\n'
    '=======================\nLoaded MCU fresh\n'
    'Error evaluating gcode_macro SMART_PARK\nfresh runtime line\n'
    % (_old.strftime('%a %b %d %H:%M:%S %Y'),
       (_now - _dt.timedelta(minutes=5)).strftime(
           '%a %b %d %H:%M:%S %Y')))
comp.log_path = _lg
r = comp._klippylog_read('3h')
check('B5 3h window: the CURRENT run survives with its runtime lines, '
      'old sections and config dumps are OUT',
      r['ok'] and 'fresh runtime line' in r['text']
      and 'SMART_PARK' in r['text']
      and 'old runtime' not in r['text']
      and 'FRESH DUMP' not in r['text']
      and 'OLD SECTION DUMP' not in r['text']
      and r['text'].startswith('# klippy.log'), r['text'][:120])
r_all = comp._klippylog_read('all')
check('B5 all window: everything (raw, capped)',
      r_all['ok'] and 'old runtime 1' in r_all['text']
      and 'fresh runtime line' in r_all['text'])
_no = os.path.join(D, 'nomarkers.log')
open(_no, 'w').write('line one\nline two\n')
comp.log_path = _no
r_no = comp._klippylog_read('day')
check('B5 foreign format (no restart markers, plain lines): still a '
      'full export (never empty)',
      r_no['ok'] and 'line one' in r_no['text']
      and 'line two' in r_no['text'])
_dm = os.path.join(D, 'dumponly.log')
open(_dm, 'w').write('===== Config file =====\n[virtual_sdcard]\n'
                     'ONLY A DUMP\n=======================\n')
comp.log_path = _dm
r_dm = comp._klippylog_read('day')
check('B5 nothing survives the filter (dump-only): NEVER an empty '
      'export - the raw tail ships with a note',
      r_dm['ok'] and 'ONLY A DUMP' in r_dm['text']
      and 'no restart markers found' in r_dm['text'])
# THE FIELD REGRESSION: the real 12 MB log (if present in uploads/)
_field = '/home/user/uploads/klippy.log.txt'
if os.path.isfile(_field):
    comp.log_path = _field
    r_day = comp._klippylog_read('day')
    _n_smart = sum(1 for l in r_day['text'].split('\n')
                   if 'SMART_PARK' in l)
    check('B5 FIELD REGRESSION: the real 12 MB klippy.log exports the '
          'day window with the SMART_PARK errors VISIBLE (the .136w '
          'export was 512 bytes, header only - 0 lines)',
          r_day['ok'] and r_day['lines'] >= 3000 and _n_smart >= 8
          and '===== Config file' not in r_day['text'],
          'lines=%d smart=%d' % (r_day['lines'], _n_smart))
else:
    print('  [i] field log not present - skipped the real-file check')

import shutil
shutil.rmtree(D, ignore_errors=True)

print()
if fails:
    print('R226 FIELD FIXES: %d checks, %d FAIL' % (N, len(fails)))
    for f in fails:
        print('  -', f)
    sys.exit(1)
print('R226 FIELD FIXES: %d checks, 0 FAIL - the .136x round is pinned' % N)
