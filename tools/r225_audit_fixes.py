info = [int(x) for x in re.findall(r'(\d+)', tls[0])]
data = ''.join(tls[1:-1])
check('A5 thumbnail: THREE ints in the begin line (w x h + base64 '
      'length) and the re-joined payload matches byte-exactly - the '
      'two-int headers of R212 were rejected with "Error parsing '
      'thumbnail header"',
      len(info) == 3 and info[:2] == [128, 128]
      and len(data) == info[2], (info, len(data)))
footer = raw[-1024 * 1024:]          # moonraker reads the last 1 MiB
