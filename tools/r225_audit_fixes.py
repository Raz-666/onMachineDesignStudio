# ================================================== A7: the stray-tag check ==
print('--- A7: one global APPLY_TYPE/;TYPE: - levels compared')


def _loop(out, e, x0, y0, w, f):
    out.append('G0 X%.1f Y%.1f F9000' % (x0, y0))
    for (x, y) in [(x0 + w, y0), (x0 + w, y0 + w), (x0, y0 + w), (x0, y0)]:
        e += w * 0.05
        out.append('G1 X%.1f Y%.1f F%d E%.3f' % (x, y, f, e))
    return e


def _hatch(out, e, x0, y0, w, h, gap, f):
    y = y0
    n = 0
    while y <= y0 + h + 0.01:
        if n % 2 == 0:
            out.append('G0 X%.1f Y%.1f F9000' % (x0, y))
            e += w * 0.05
            out.append('G1 X%.1f Y%.1f F%d E%.3f' % (x0 + w, y, f, e))
        else:
            out.append('G0 X%.1f Y%.1f F9000' % (x0 + w, y))
            e += w * 0.05
            out.append('G1 X%.1f Y%.1f F%d E%.3f' % (x0, y, f, e))
        y += gap
        n += 1
    return e


def _build(stray=None, walls_only=False):
    out = ['; generated by MysterySlicer 0.9', 'M82', 'G28', 'G90',
           'M104 S200', 'M140 S60']
    if stray:
        out.append(stray)
    e = 0.0
    for z in (0.2, 0.4, 0.6):
        out.append('G0 X5 Y5 Z%.1f F9000' % z)
        e = _loop(out, e, 50, 50, 40, 1800)
        e = _loop(out, e, 55, 55, 30, 1800)
        if not walls_only:
            e = _hatch(out, e, 56, 56, 28, 28, 1.0 if z != 0.4 else 6.0,
                       1800 if z != 0.4 else 4800)
    out += ['M104 S0', 'M140 S0']
    return out


def _types(p):
    return set(re.findall(r'APPLY_TYPE TYPE=(\S+)', open(p).read()))


