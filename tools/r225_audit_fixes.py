class _FakeServer:
    def __init__(self):
        self.endpoints = {}

    def register_endpoint(self, ep, methods, cb):
        self.endpoints[ep] = cb

    def register_remote_method(self, name, cb):
        pass

    def add_log_rollback_handler(self, cb):
        pass


class FakeConfig:
    def __init__(self, path, export_tool=None):
        self.path = path
        self.export_tool = export_tool
        self.server = _FakeServer()

    def get(self, key, default):
        if key == 'path':
            return self.path
        if key == 'export_tool':
            return self.export_tool if self.export_tool is not None else default
        return default

    def get_server(self):
        return self.server


