"""R225 (.136w): regression pins for the audit round + the two user
feature requests.

  A1  web refresh: the export tool is DERIVED from the menu json path
      (.../web/menu_structure.json -> .../tools/menu_json_export.py in
      the same package root). The $HOME default only exists in the dev
      sandbox - on the documented Pi install the package lives under
      ~/printer_data/config/ and the field refresh silently reloaded
      the STALE embedded json (r197 T2 ran green by accident).
      Precedence: explicit export_tool > derived > default.
  A2  install_web.sh writes export_tool into a NEW [r2_menu] section and
      patches an EXISTING one (sections from before .136w lack the line).
  A3  update.sh says 19 modules (it checks 19; the text said 17).
  A4  Cura fallback: without ;LAYER:/;TYPE: the object box goes BEFORE
      the first print command (PRINT_START), never behind PRINT_END.
  A5  Mainsail metadata, verified against moonraker's REAL parser
      (components/file_manager/metadata.py, master 2026):
      3-int thumbnail header + payload length, meta block in the FOOTER
      (the PrusaSlicer parser class reads the footer), identify stamp
      '; generated by R2-D2 <release> on <date> at <time>' in the header
      (UnknownSlicer hardcodes time/filament to None - only the Prusa
      chain extracts them at all), trailing newline, old-layout blocks
      self-heal once (fmt=2), slicer files stay untouched.
  A6  feature vocabulary from uploads/slicer-families.md: Simplify3D's
      '; feature x' space dialect, FlashPrint ;structure:, Kiri:Moto
      bare words, KISSlicer faces/crown, S3D single extrusion, ideaMaker
      shells/towers, Orca CamelCase placeholders + aggregate roles.
  A7  the user's APPLY_TYPE stray-tag question: ONE global tag over a
      multi-feature file is re-derived from geometry (levels compared,
      STRAYTAG names the tag); geometry that AGREES keeps the tag;
      multi-tag files stay tagged; the R213 CUSTOM/C1 path is exempt.

Run: python3 tools/r225_audit_fixes.py   (exit 0 = all green)
"""
