def _write_c_channel_sliced(path, layers=24, layer_h=0.2):
    """Konkaves U-/C-Profil (Außenmaß 56×50 mm um Bettmitte 110/110, tiefe Bucht
    rechts offen) im echten Orca/Prusa-Slicer-Format mit ;LAYER_CHANGE, ;Z:,
    ;HEIGHT:, ;WIDTH:, ;TYPE:Outer wall, M83 (Relativ-Extrusion mit Kommentar,
    prüft den R73-Kommentar-Stripper!) sowie Start-/Endtemperaturen."""
    # Konkaves C-Polygon um (110, 110): X=82..138, Y=85..135, Bucht X=120..138, Y=97..123
    # (Rücken X=82..120 enthält das BBox-Zentrum (110, 110), sodass Fl.hole sichtbar im Vollmaterial sitzt!)
    poly_out = [
        (82.0, 85.0), (138.0, 85.0), (138.0, 97.0), (120.0, 97.0),
        (120.0, 123.0), (138.0, 123.0), (138.0, 135.0), (82.0, 135.0),
    ]
    poly_in = [
        (83.2, 86.2), (136.8, 86.2), (136.8, 95.8), (118.8, 95.8),
        (118.8, 124.2), (136.8, 124.2), (136.8, 133.8), (83.2, 133.8),
    ]
    k_e = 0.036
    with open(path, 'w', encoding='utf-8') as f:
        f.write('; generated by OrcaSlicer synthetic fixture for RANGE.pdf\n')
        f.write('; filament_type = PETG\n')
        f.write('M140 S70\nM104 S235\nM190 S70\nM109 S235\n')
        f.write('G90\n')
        f.write('M83 ; use relative distances for extrusion\n')
        f.write('EXCLUDE_OBJECT_DEFINE NAME=C_PROFIL CENTER=110.0,110.0\n')
        f.write('M204 P1500\nM106 S128\n')
        for i in range(1, layers + 1):
            z = round(i * layer_h, 3)
            f.write(';LAYER_CHANGE\n;Z:%.3f\n;HEIGHT:%.3f\n' % (z, layer_h))
            f.write('G0 Z%.3f F6000\n' % z)
            f.write(';TYPE:Inner wall\n;WIDTH:0.45\n')
            f.write('G0 X%.3f Y%.3f F7200\n' % poly_in[0])
            px, py = poly_in[0]
            for qx, qy in poly_in[1:] + [poly_in[0]]:
                de = math.hypot(qx - px, qy - py) * k_e
                f.write('G1 X%.3f Y%.3f E%.5f F2400\n' % (qx, qy, de))
                px, py = qx, qy
            f.write(';TYPE:Outer wall\n;WIDTH:0.42\n')
            f.write('G0 X%.3f Y%.3f F7200\n' % poly_out[0])
            px, py = poly_out[0]
            for qx, qy in poly_out[1:] + [poly_out[0]]:
                de = math.hypot(qx - px, qy - py) * k_e
                f.write('G1 X%.3f Y%.3f E%.5f F1800\n' % (qx, qy, de))
                px, py = qx, qy
        f.write('M104 S0\nM140 S0\nM84\n')
    pp.process(path)
    return path


def _parse_layers_and_segs(gcode_path):
    """Liest alle extrudierenden Segmente samt ihrer Z-Höhe und aktivem APPLY_TYPE."""
    segs = []
    px = py = pz = None
    last_e = 0.0
    e_rel = False
    cur_type = 'BODY'
    with open(gcode_path, encoding='utf-8', errors='replace') as f:
        for raw in f:
            ls = raw.split(';', 1)[0].strip()
            if not ls:
                continue
            if ls == 'M83':
                e_rel = True
                continue
            if ls == 'M82':
                e_rel = False
                continue
            if ls.startswith('G92'):
                m = re.search(r'E(-?[\d.]+)', ls)
                if m:
                    last_e = float(m.group(1))
                continue
            if ls.startswith('APPLY_TYPE'):
                m = re.search(r'TYPE=(\S+)', ls)
                if m:
                    cur_type = m.group(1)
                continue
            if ls.startswith(('G0 ', 'G1 ')):
                mx = re.search(r'X(-?[\d.]+)', ls)
                my = re.search(r'Y(-?[\d.]+)', ls)
                mz = re.search(r'Z(-?[\d.]+)', ls)
                me = re.search(r'E(-?[\d.]+)', ls)
                nx = float(mx.group(1)) if mx else px
                ny = float(my.group(1)) if my else py
                nz = float(mz.group(1)) if mz else pz
                de = 0.0
                if me:
                    ev = float(me.group(1))
                    de = ev if e_rel else (ev - last_e)
                    if not e_rel:
                        last_e = ev
                if de > 1e-6 and px is not None and nx is not None:
                    segs.append((px, py, nx, ny, round(nz or 0.2, 3), de, cur_type))
                px, py, pz = nx, ny, nz
    zs = sorted(set(s[4] for s in segs))
    return zs, segs


def _parse_range_menu():
    cfg = os.path.join(REPO, 'menus', 'lcd_menues.cfg')
    txt = open(cfg, encoding='utf-8').read()
    rows = []
    for blk in re.split(r'(?=^\[menu )', txt, flags=re.M):
        m = re.match(r'^\[menu (__main __preprint __mods __rng[^\]]*)\]', blk)
        if not m:
            continue
        sec = m.group(1).strip()
        if sec == '__main __preprint __mods __rng':
            continue
        key = sec.split()[-1]
        nm = re.search(r'^\s*name:\s*(.+)$', blk, re.M)
        imin = re.search(r'^\s*input_min:\s*(.+)$', blk, re.M)
        imax = re.search(r'^\s*input_max:\s*(.+)$', blk, re.M)
        istp = re.search(r'^\s*input_step:\s*(.+)$', blk, re.M)
        sv = re.search(r'SAVE_VARIABLE\s+VARIABLE=([a-z0-9_]+)', blk)
        act = re.search(r'^\s*(SET_STOP_AT_LAYER|SET_LAYER_RANGE|RESPOND)', blk, re.M)
        label = nm.group(1).strip().strip("'\"") if nm else key
        # Lange Jinja-Ausdrücke in der Tabellenansicht lesbar kürzen
        if 'total_layers' in label:
            label = 'File: &lt;N L / select first&gt;'
        elif 'FOOTPRINT' in label:
            label = label.split('{')[0].strip() + ' FOOTPRINT | OUTLINE'
        elif 'GRID' in label:
            label = label.split('{')[0].strip() + ' GRID | SOLID'
        elif 'menu.input' in label:
            prefix = label.split('{')[0].strip()
            suffix = label.split('}')[-1].strip()
            label = '%s &lt;Wert&gt;%s' % (prefix, suffix)
        else:
            label = label.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        if imin and imax and istp:
            mx_txt = imax.group(1).strip()
            if 'total_layers' in mx_txt:
                mx_txt = 'N-1' if '- 1' in mx_txt else 'N'
            rng = '%s .. %s (Schritt %s)' % (
                imin.group(1).strip(), mx_txt, istp.group(1).strip())
        else:
            rng = 'Befehl / Info'
        var = ('sv.%s' % sv.group(1)) if sv else (act.group(1) if act else '—')
        rows.append((key, label, rng, var))
    return rows


