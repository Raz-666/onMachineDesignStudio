#!/usr/bin/env python3
"""R215 field-log test battery (.136l -> .136m, 2026-10-31).

The .136l field log (klippy.log + web console) showed the printer
practically unusable: >= 4 MCU 'Timer too close' shutdowns, all at print
start / homing. The analysis found a chain of FOUR independent loads
piling onto the Pi Zero 2 W while klipper needed its reactor for
just-in-time move scheduling:

  1. the watcher scan re-analyzed + REWROTE every generated file on every
     pass (gcode_meta.finalize had no change guard) - mtimes churned, the
     gen_files list flip-flopped every few seconds, the SD card was
     written continuously, klippy logged 255 'Reactor busy' entries (up
     to 0.694 s) in eight minutes
  2. the gen_files push fired on every order flip (equal-mtime rotation)
  3. a pass that started before the print start kept pushing variables
     DURING homing (pushes at 14:18:12/:20, homing since :08, shutdown
     at :24)
  4. the web page's live poll queried configfile:None - klippy serialized
     the ENTIRE config (megabytes) every 3 s while the page was open
     (the 0.197 s stall that killed the 14:18 homing was exactly this
     query), and the page kept polling through the start phase

Plus two straight bugs:
  - 'Unknown gcode_macro variable fecho_c1/fov_c1': R213's custom slots
    c1..c9 were SET but never DECLARED - _SYNC_OV_FEAT died at c1, so the
    c1..c9 mirrors never synced and the echo silencer never armed
  - 79x 'Neopixel update did not succeed' (confirmations lost while the
    reactor stalled): the long-running + start-phase LED effects drop
    12 -> 6 fps (guarded in r164)

This battery pins every fix functionally (where possible) and by source
shape (where the code only lives inside the daemon loop or the page).
"""
import importlib.util
import os
import re
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
RUNS = [0]
FAILS = []


def check(name, cond, detail=''):
    RUNS[0] += 1
    if cond:
        print('PASS  %s%s' % (name, (' - ' + detail) if detail else ''))
    else:
        print('FAIL  %s%s' % (name, (' - ' + detail) if detail else ''))
        FAILS.append(name)


# ---------------------------------------------------------------- T1: vars
state = open(os.path.join(REPO, 'macros', '01_state.cfg'),
             encoding='utf-8').read()
_missing = [n for k in range(1, 10) for n in ('fov_c%d' % k, 'fecho_c%d' % k)
            if ('variable_%s:' % n) not in state]
check('T1 _STATE declares fov_c1..c9 + fecho_c1..c9 (the R213 unknown-'
      'variable errors)', not _missing, 'missing: %s' % (_missing or 'none'))
_sync = open(os.path.join(REPO, 'macros', '10_live_tuning.cfg'),
             encoding='utf-8').read()
check('T1b _SYNC_OV_FEAT loops the c1..c9 names it sets',
      all(("'%s'" % k) in _sync for k in
          ['c1', 'c5', 'c9']) and 'fov_{c|lower}' in _sync)

# ---------------------------------------------------- T2: gcode_meta guard
sys.path.insert(0, HERE)
import gcode_meta                                            # noqa: E402

d = tempfile.mkdtemp(prefix='r215_')
p = os.path.join(d, 'gen.gcode')
open(p, 'w').write(
    '; R2-GEN core R2-2026-10-31.136m (R204)\n'
    'G28\nG1 X10 Y10 E1 F1200\nG1 X20 Y10 E2\nG1 X20 Y20 E3\n')
r1 = gcode_meta.finalize(p)
m1, s1 = os.path.getmtime(p), os.path.getsize(p)
time.sleep(0.02)
r2 = gcode_meta.finalize(p)
m2, s2 = os.path.getmtime(p), os.path.getsize(p)
r3 = gcode_meta.finalize(p)
check('T2 gcode_meta: first pass writes, repeat passes return "same"',
      (r1, r2, r3) == ('meta', 'same', 'same'), '%r %r %r' % (r1, r2, r3))
check('T2b gcode_meta: "same" does not touch the file (mtime+size stable)',
      (m1, s1) == (m2, s2))
with open(p, 'a') as f:
    f.write('G1 X30 Y20 E4\n')
check('T2c gcode_meta: a body change triggers exactly one refresh',
      gcode_meta.finalize(p) == 'meta'
      and gcode_meta.finalize(p) == 'same')
p2 = os.path.join(d, 'old.gcode')
open(p2, 'w').write(
    'G28\nG1 X10 Y10 E1 F1200\nG1 X20 Y10 E2\n'
    '; R2-META v1\n; generated by R2-D2 (klipper-e3-r2d2) - meta from its own moves\n'
    '; estimated printing time (normal mode) = 0s\n; filament used [mm] = 12.0mm\n'
    'G1 X20 Y20 E3\n')
check('T2d gcode_meta: a pre-sig block migrates once, then stays "same"',
      gcode_meta.finalize(p2) == 'meta'
      and gcode_meta.finalize(p2) == 'same')
raw = open(p, encoding='utf-8', errors='replace').read()
# R258 added '; total layers count' between filament and sig - the sig
# stays the LAST line of the block (and of the file)
check('T2e gcode_meta: the block ends with the sig line, 16 hex chars',
      re.search(r'; R2-META sig = [0-9a-f]{16}$', raw, re.M) is not None
      and not raw.rstrip('\n').split('\n')[-1].startswith('G'))

# ---------------------------------------------- T3: daemon source shapes
pp = open(os.path.join(REPO, 'tools', 'r2_postproc.py'),
          encoding='utf-8').read()
check('T3 gen_files order is STICKY (set unchanged -> keep pushed order)',
      'set(_gfl) == set(gen_files_pushed[0])' in pp)
# R246c hardened the probe: _printer_idle_strict() (an UNANSWERED probe
# counts as busy - the .142 00:08 frame print died on exactly that gap).
# R247 moved the tree daemon-side; the guard now sits between the walk
# and the sd_cur/gen push comparison.
check('T3b pushes are guarded by a FRESH busy probe mid-pass '
      '(_SkipPush215 raises before the pushes)',
      'class _SkipPush215' in pp and 'except _SkipPush215' in pp
      and pp.index('if not _printer_idle_strict():',
                   pp.index('_walk154(' + chr(39)*2 + ')'))
      < pp.index('sd_tree_pushed[0] = _tree154'))
check('T3c _meta_finalize stays silent on "same"',
      "'same' = signature matched, nothing written" in pp)
check('T3d HOST_CHECK shows klippy reactor symptoms',
      'def _klippy_reactor_stats' in pp and 'def _reactor_verdict' in pp
      and '_reactor_verdict(_klippy_reactor_stats())' in pp)

# ---------------------------------------------- T4: reactor stats helpers
spec = importlib.util.spec_from_file_location(
    'r2pp', os.path.join(REPO, 'tools', 'r2_postproc.py'))
r2pp = importlib.util.module_from_spec(spec)
spec.loader.exec_module(r2pp)
log = os.path.join(d, 'klippy.log')
open(log, 'w').write(
    'Stats 1.0: gcodein=0\n'
    'Reactor 109217.294 busy for 0.694 with:\n'
    "- 'QueryStatusHelper._do_query (webhooks.py:487)',\n"
    'Neopixel update did not succeed\n'
    'Neopixel update did not succeed\n'
    'Reactor 109219.085 busy for 0.242 with:\n')
rs = r2pp._klippy_reactor_stats(log)
check('T4 _klippy_reactor_stats counts stalls + neopixel failures',
      rs == (2, 0.694, 2), repr(rs))
ok, line = r2pp._reactor_verdict(rs)
check('T4b a pressured reactor flips the HOST_CHECK verdict to not-ok',
      ok is False and '0.694s' in line and '2 failed LED' in line, line)
ok2, line2 = r2pp._reactor_verdict((0, 0.0, 0))
check('T4c a clean reactor reads as clean (homing is safe)',
      ok2 is True and 'no stalls' in line2)
check('T4d a missing log degrades to a note, not an error',
      r2pp._reactor_verdict(None)[1].startswith('Reactor: klippy.log not found'))

# ------------------------------------------------ T5: r2_menu query shape
r2m_src = open(os.path.join(REPO, 'web', 'r2_menu.py'), encoding='utf-8').read()
check('T5 r2_menu requests configfile as "settings" (not the full object '
      'with the raw config text)',
      "('settings' if o == 'configfile' else None)" in r2m_src)

# ------------------------------------------------- T6: web page quiet win
html = open(os.path.join(REPO, 'web', 'index.html'), encoding='utf-8').read()
check('T6 page has a 25 s start quiet window (QUIETUNTIL + startQuiet)',
      'QUIETUNTIL' in html and 'function startQuiet(){QUIETUNTIL=Date.now()+25000;}' in html)
check('T6b pollAll skips the live fetch inside the quiet window but keeps '
      'the console store',
      'if(Date.now()>=QUIETUNTIL){try{' in html
      and 'gcode_store?count=300' in html)
check('T6c both send paths arm the quiet window on start-type commands',
      html.count('SDCARD_PRINT_FILE|PRINT_AS_|PRINT_START|RESUME') == 2)

# ------------------------------------------------------ T7: LED frame diet
led = open(os.path.join(REPO, 'macros', '03_leds.cfg'), encoding='utf-8').read()
_fr = {}
for e in ('r2_idle', 'r2_waiting', 'r2_heating', 'r2_homing', 'r2_leveling',
          'r2_pid', 'r2_nozzle_on'):
    m = re.search(r'\[led_effect %s\].*?frame_rate:\s*(\d+)' % e, led, re.S)
    if m:
        _fr[e] = int(m.group(1))
check('T7 long-running + start-phase LED effects at <= 6 fps '
      '(12 fps fed ledFrameHandler into the busy stacks)',
      len(_fr) == 7 and all(v <= 6 for v in _fr.values()), str(_fr))

# ------------------------------------------------------------------ outro
print()
if FAILS:
    print('==== R215 FIELD FIXES: %d checks, %d FAIL ====' % (RUNS[0], len(FAILS)))
    for f in FAILS:
        print('     ' + f)
    sys.exit(1)
print('==== R215 FIELD FIXES: %d checks, 0 FAIL - all fixes pinned ====' % RUNS[0])
