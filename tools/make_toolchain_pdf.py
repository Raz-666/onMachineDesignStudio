def _fig_noncommutativity(chain_ab_path, chain_ba_path, out_png):
    """Beweist die Nicht-Kommutativität T_2(T_1(G)) != T_1(T_2(G)) direkt an den
    echten Ausgaben von toolchain.run_chain():
      Links : Kette A = Scale(X=160%, Y=65%) -> Twist(+90°)
      Rechts: Kette B = Twist(+90°)          -> Scale(X=160%, Y=65%)
    Gezeigt werden jeweils Fußschicht (Z=0,2 mm, grau) und Kopfschicht (Z=10,0 mm,
    farbig) sowie Mittel-Schicht (Z=5,0 mm, gestrichelt/hell)."""
    W, H = 1280, 520
    im = PILImage.new('RGB', (W, H), 'white')
    d = ImageDraw.Draw(im)
    f_b = font(19, bold=True)
    f_m = font(15, bold=True)
    f_xs = font(13)

    d.text((45, 14),
           'Echter Nicht-Kommutativitäts-Beweis aus run_chain(): Scale -> Twist  !=  Twist -> Scale',
           font=f_b, fill='#1c4e8c')

    panels = [
        ('A) Erst Scale(160/65 %), dann Twist(+90°)',
         chain_ab_path, '#1c4e8c',
         'Fuß: 64×29 mm  |  Kopf (90° gedreht): 29×64 mm  (formtreu gedreht!)'),
        ('B) Erst Twist(+90°), dann Scale(160/65 %)',
         chain_ba_path, '#b3261e',
         'Fuß: 64×29 mm  |  Kopf: 72×26 mm  (erst gedreht, dann wieder breit gezogen!)'),
    ]

    for idx, (title, pth, col_top, caption_line) in enumerate(panels):
        bx0 = 45 + idx * 610
        by0, bw, bh = 62, 575, 405
        d.rectangle([bx0, by0, bx0 + bw, by0 + bh], outline='#8aa4c2',
                    width=2, fill='#f9fbfe')
        d.text((bx0, by0 - 24), title, font=f_m, fill=col_top)

        cx_p, cy_p = bx0 + bw // 2, by0 + bh // 2
        sc = 4.2

        def map_xy(x, y):
            return cx_p + (x - 110.0) * sc, cy_p - (y - 110.0) * sc

        d.line([bx0 + 25, cy_p, bx0 + bw - 25, cy_p], fill='#e3ebf4', width=1)
        d.line([cx_p, by0 + 25, cx_p, by0 + bh - 25], fill='#e3ebf4', width=1)

        segs = _parse_segs(pth)
        for sz, col_l, w_l in ((0.2, '#8b99a8', 3),
                               (5.0, '#e07b00', 2),
                               (10.0, col_top, 4)):
            for x0, y0, x1, y1, z, _de in segs:
                if abs(z - sz) < 0.05:
                    d.line([map_xy(x0, y0), map_xy(x1, y1)], fill=col_l, width=w_l)

        d.text((bx0 + 16, by0 + 14),
               'Grau = Fuß (Z=0,2)   |   Orange = Mitte (Z=5,0)   |   Kräftig = Kopf (Z=10,0)',
               font=f_xs, fill='#333333')
        d.text((bx0 + 16, by0 + bh - 28), caption_line, font=f_xs, fill=col_top)

    d.text((45, H - 34),
           'Merksatz für die Praxis: In 95 % aller Fälle willst du A (erst Maß setzen, dann verdrehen) — niemals umgekehrt!',
           font=f_xs, fill='#1e7d32')
    im.save(out_png)


