def _write_marked_tower(path, w=40.0, d=40.0, layers=50, layer_h=0.2):
    """40×40×10-mm-Quadratturm (50 Schichten) mit kleiner asymmetrischer Nase an
    der Nordwand (zeigt Orientierung & Spiegelung eindeutig), vollständig
    vorverarbeitet über r2_postproc.process() (echte LAYER_MARKs für Range!)."""
    cx, cy = 110.0, 110.0
    x0, x1 = cx - w / 2.0, cx + w / 2.0
    y0, y1 = cy - d / 2.0, cy + d / 2.0
    # Quadrat mit asymmetrischer Kerbnase rechts oben an der Nordwand
    poly = [
        (x0, y0), (x1, y0), (x1, y1),
        (cx + 10.0, y1), (cx + 7.0, y1 + 5.0), (cx + 2.0, y1),
        (x0, y1),
    ]
    k_e = 0.034
    with open(path, 'w', encoding='utf-8') as f:
        f.write('; generated by OrcaSlicer synthetic fixture for TOOLCHAIN.pdf\n')
        f.write('; filament_type = PLA\n')
        f.write('M140 S60\nM104 S210\nG90\nM83\n')
        f.write('EXCLUDE_OBJECT_DEFINE NAME=TURM CENTER=110.0,110.0\n')
        for i in range(1, layers + 1):
            z = round(i * layer_h, 3)
            f.write(';LAYER_CHANGE\n;Z:%.3f\n;HEIGHT:%.3f\n' % (z, layer_h))
            f.write('G0 Z%.3f F6000\n' % z)
            f.write(';TYPE:Outer wall\n;WIDTH:0.42\n')
            f.write('G0 X%.3f Y%.3f F7200\n' % poly[0])
            px, py = poly[0]
            for qx, qy in poly[1:] + [poly[0]]:
                de = math.hypot(qx - px, qy - py) * k_e
                f.write('G1 X%.3f Y%.3f E%.5f F1800\n' % (qx, qy, de))
                px, py = qx, qy
        f.write('M104 S0\nM140 S0\nM84\n')
    pp.process(path)
    return path


def _parse_segs(gcode_path):
    segs = []
    px = py = pz = None
    last_e = 0.0
    e_rel = False
    with open(gcode_path, encoding='utf-8', errors='replace') as f:
        for raw in f:
            ls = raw.split(';', 1)[0].strip()
            if not ls:
                continue
            if ls == 'M83':
                e_rel = True
                continue
            if ls == 'M82':
                e_rel = False
                continue
            if ls.startswith('G92'):
                m = re.search(r'E(-?[\d.]+)', ls)
                if m:
                    last_e = float(m.group(1))
                continue
            if ls.startswith(('G0 ', 'G1 ')):
                mx = re.search(r'X(-?[\d.]+)', ls)
                my = re.search(r'Y(-?[\d.]+)', ls)
                mz = re.search(r'Z(-?[\d.]+)', ls)
                me = re.search(r'E(-?[\d.]+)', ls)
                nx = float(mx.group(1)) if mx else px
                ny = float(my.group(1)) if my else py
                nz = float(mz.group(1)) if mz else pz
                de = 0.0
                if me:
                    ev = float(me.group(1))
                    de = ev if e_rel else (ev - last_e)
                    if not e_rel:
                        last_e = ev
                if de > 1e-6 and px is not None and nx is not None:
                    segs.append((px, py, nx, ny, round(nz or 0.2, 3), de))
                px, py, pz = nx, ny, nz
    return segs


def _bbox_and_e(gcode_path, only_z=None):
    segs = _parse_segs(gcode_path)
    if only_z is not None:
        segs_z = [s for s in segs if abs(s[4] - only_z) < 0.05]
    else:
        segs_z = segs
    xs = [s[0] for s in segs_z] + [s[2] for s_z in [segs_z] for s in s_z]
    ys = [s[1] for s in segs_z] + [s[3] for s_z in [segs_z] for s in s_z]
    return (min(xs), max(xs), min(ys), max(ys)), sum(s[5] for s in segs), segs


def _parse_menu_branch(branch):
    cfg = os.path.join(REPO, 'menus', 'lcd_menues.cfg')
    txt = open(cfg, encoding='utf-8').read()
    rows = []
    target_root = '__main __preprint __mods %s' % branch
    for blk in re.split(r'(?=^\[menu )', txt, flags=re.M):
        m = re.match(r'^\[menu (__main __preprint __mods %s[^\]]*)\]' % re.escape(branch), blk)
        if not m:
            continue
        sec = m.group(1).strip()
        if sec == target_root:
            continue
        key = sec.split()[-1]
        nm = re.search(r'^\s*name:\s*(.+)$', blk, re.M)
        imin = re.search(r'^\s*input_min:\s*(.+)$', blk, re.M)
        imax = re.search(r'^\s*input_max:\s*(.+)$', blk, re.M)
        istp = re.search(r'^\s*input_step:\s*(.+)$', blk, re.M)
        act = re.search(r'^\s*(TOOLCHAIN_APPLY|SET_GCODE_OFFSET|RESPOND)', blk, re.M)
        label = nm.group(1).strip().strip("'\"") if nm else key
        if 'toolchain_preset' in label:
            label = 'Preset: &lt;aktuelle .json&gt;'
        elif '_PREVIEW' in label:
            label = 'File: &lt;gewählte .gcode&gt;'
        elif 'gen_arm' in label:
            label = '&gt; Apply  (2. Klick: &gt; AGAIN = start)'
        elif 'menu.input' in label:
            prefix = label.split('{')[0].strip()
            label = '%s &lt;-5,00..+5,00&gt;' % prefix
        else:
            label = label.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')
        rng = ('%s .. %s mm (Schritt %s)'
               % (imin.group(1).strip(), imax.group(1).strip(),
                  istp.group(1).strip())) if (imin and imax and istp) else 'Befehl / Anzeige'
        rows.append((key, label, rng, act.group(1) if act else '—'))
    return rows


