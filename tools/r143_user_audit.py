        if l.startswith('APPLY_TYPE TYPE='):
            cur['applies'].append(l.split('=', 1)[1])
        m = re.match(r'G1 X(-?[\d.]+) Y(-?[\d.]+).*E', l)
        if m and x is not None:
            dx, dy = float(m.group(1)) - x, float(m.group(2)) - y
            cur['geo'].append(round((dx * dx + dy * dy) ** 0.5, 1))
        if m:
            x, y = float(m.group(1)), float(m.group(2))
        else:
            m2 = re.match(r'G[01] X(-?[\d.]+) Y(-?[\d.]+)', l)
            if m2:
                x, y = float(m2.group(1)), float(m2.group(2))
