def _loop(x0, y0, w, n=8):
    import math as _m
    pts = []
    for i in range(n):
        a = 2 * _m.pi * i / n
        pts.append((x0 + w / 2 + w / 2 * _m.cos(a),
                    y0 + w / 2 + w / 2 * _m.sin(a)))
    pts.append(pts[0])          # CLOSED loop (the classifier requires it)
    return pts

def _emit_poly(o, pts, e):
    for j, (x, y) in enumerate(pts):
        if j == 0:
            o.append('G0 X%.2f Y%.2f F9000' % (x, y))
        else:
            e += 0.8
            o.append('G1 X%.2f Y%.2f F2400 E%.3f' % (x, y, e))
    return e

