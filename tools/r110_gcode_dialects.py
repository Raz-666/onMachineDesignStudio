def _prusa_txt():
    for d in DIALECTS:
        if d[0] == 'prusa':
            return build(d)[0]
    return ''


LAYER_STYLE = {
    'orca': [';LAYER_CHANGE'],
    'prusa': [';LAYER_CHANGE'],
    'cura': [';LAYER:0', ';LAYER:1'],
    'kiri': [';LAYER 0', ';LAYER 1'],
    's3d': ['; layer 1', '; layer 2'],
    'zscan': [],
    'ztravel': [],
}


def build(dialect):
    fname, header, types, style, emode, slicer = dialect
    z = [0.2, 0.4]
    lay = LAYER_STYLE[style]
    out = [header.rstrip('\n'), emode, 'G28', 'G90', 'M104 S200', 'M140 S60']
    e = 0.0
    for i in range(2):
        if lay:
            out.append(lay[i % len(lay)])
        if style == 'ztravel':
            # the layer's Z rides on a TRAVEL line only (modal-Z territory)
            out.append('G0 X5 Y5 Z%.1f F9000' % z[i])
        first_of_layer = True
        if not types:
            # untagged dialect: plain extruding moves (walls + infill, no ;TYPE:)
            for k in range(3):
                e += 0.35
                zz = ' Z%.1f' % z[i] if first_of_layer else ''
                out.append('G1 X%d.%d Y%d%s F%d E%.3f'
                           % (30 + k, i, 30 + k, zz, 2400, e))
                first_of_layer = False
            out.append('G0 X5 Y5 F9000')
            continue
        for canon, spell in types.items():
            f, acc = FEATS[canon]
            if spell is not None:
                out.append(';TYPE:%s' % spell)
            out.append('M204 S%d' % acc)
            for k in range(3):
                # M82 values must accumulate; repeated E0 is not extrusion.
                e += 0.35
                ee = ('E%.3f' % e) if emode == 'M82' else ('E%.3f' % 0.35)
                # Z-scan dialects: Z rides ON the first extruding move of the
                # layer (the classic combined-move pattern _ZScan reads)
                zz = ' Z%.1f' % z[i] if (first_of_layer and not lay and style != 'ztravel') else ''
                out.append('G1 X%d.%d Y%d%s F%d %s'
                           % (30 + k, i, 30 + k, zz, f, ee))
                first_of_layer = False
            if emode == 'M83':
                e = 0.35  # per-block relative resets visually
        out.append('G0 X5 Y5 F9000')
    out.append('M104 S0')
    out.append('M140 S0')
    txt = '\n'.join(out) + '\n'
    if fname == 'marlin-volumetric':
        # mm3-scale extrusions + the explicit marker
        txt = re.sub(r'E\d+\.\d+', lambda m: 'E0%.4f' % (float(m.group(0)[1:]) / 100), txt)
    return txt, set(types.keys()), 2, slicer


def info_block(path):
    txt = open(path, errors='replace').read()
    i = txt.find('_FILE_INFO ')
    if i < 0:
        return ''
    j = txt.find('\n', i)
    return txt[i:j if j > 0 else None]


fails = []
hits_total = 0
tagged_total = 0


def check(name, ok, info=''):
    if not ok:
        fails.append(name)
        print('  FAIL %s %s' % (name, str(info)[:200]))


for dialect in DIALECTS:
    name = dialect[0]
    print('--- %s ' % name.ljust(20, '-'))
    txt, truth_types, truth_layers, slicer = build(dialect)
    path = os.path.join(D, name + '.gcode')
    open(path, 'w', newline='' if name != 'crlf' else '\r\n').write(txt)

    summ = pp.process(path)
    body = open(path, errors='replace').read()
    fi = info_block(path)

    check('%s: processed, not skipped' % name,
          summ and not summ.get('skipped') and '; R2-POSTPROC v5' in body)
    check('%s: _FILE_INFO present' % name, '_FILE_INFO ' in body)

    # layer marks. R258 (Option B): _FILE_INFO TOTAL_LAYERS is the physical
    # positive-extrusion layer count in BOTH detector worlds. The Z-scan
    # still inserts one mark per layer RISE (layer 1 needs no mark - it
    # begins at print start), the comment detector inserts one mark per
    # comment; the reported count is rises+1 either way.
    marks = body.count('LAYER_MARK')
    check('%s: TOTAL_LAYERS == %d (physical)' % (name, truth_layers),
          summ.get('layers', 0) == truth_layers, summ.get('layers'))
    if LAYER_STYLE[dialect[3]]:
        check('%s: LAYER_MARK == %d' % (name, truth_layers), marks == truth_layers, marks)
    else:
        check('%s: Z-scan marks == rises (%d)' % (name, truth_layers - 1),
              marks == truth_layers - 1, marks)

    # TYPES
    m = re.search(r'TYPES=([^\s]*)', fi)
    got = set(m.group(1).split(',')) if m and m.group(1) else set()
    if truth_types:
        check('%s: TYPES == ground truth' % name, got == truth_types,
              'got=%s want=%s' % (sorted(got), sorted(truth_types)))
    hits_total += len(got & truth_types)
    tagged_total += len(truth_types)

    # FS values
    for canon in truth_types:
        if not canon.startswith('WALL-INNER2'):
            canon = canon
        key = canon.replace('-', '_').replace('WALL_INNER2', 'WALL_INNER')
        m = re.search(r'FS_%s=([0-9.]+)' % key, fi)
        check('%s: FS_%s' % (name, canon),
              m and abs(float(m.group(1)) - SPEED[canon]) < 0.01,
              m.group(1) if m else 'missing')

    # APPLY_TYPE after every ;TYPE: line of this dialect
    ntypes = len([l for l in body.splitlines() if l.startswith(';TYPE:')])
    if dialect[2]:
        check('%s: APPLY_TYPE coverage' % name,
              body.count('APPLY_TYPE') >= ntypes, (body.count('APPLY_TYPE'), ntypes))

    # slicer / firmware / volumetric detection
    det = pp._detect_slicer(path)
    if slicer:
        check('%s: slicer detected as %s' % (name, slicer), det['slicer'].startswith(slicer),
              det['slicer'])
    if name == 'marlin-volumetric':
        check('%s: volumetric detected' % name, det['volumetric'] is True)

    # idempotency
    summ2 = pp.process(path)
    check('%s: second run skips' % name, summ2.get('skipped') is True)

print()
print('tagged-feature hit rate on the corpus: %d/%d (%.0f%%)'
      % (hits_total, tagged_total, 100.0 * hits_total / max(1, tagged_total)))
if fails:
    print('R110 DIALECT CORPUS: %d FAILURE(S)' % len(fails))
    sys.exit(1)
print('R110 DIALECT CORPUS: all %d families passed' % len(DIALECTS))
