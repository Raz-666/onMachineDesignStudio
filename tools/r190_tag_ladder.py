def _feature_sequence(text):
    """[(layer_no, feature)] from LAYER_MARK + ;TYPE:/APPLY_TYPE lines."""
    seq = []
    layer = 0
    cur = None
    for l in text.split('\n'):
        if l.strip() == 'LAYER_MARK':
            layer += 1
            cur = None
            continue
        if l.strip().startswith(';TYPE:'):
            cur = _canon_type(l.split(':', 1)[1])
        elif l.strip().startswith('APPLY_TYPE TYPE='):
            cur = l.split('TYPE=', 1)[1].strip()
        if cur and (not seq or seq[-1] != (layer, cur)):
            seq.append((layer, cur))
    return seq


