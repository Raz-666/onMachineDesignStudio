def _hatchf(x0, y0, x1, y1, step, e=0.5, f=2700):
    out, up, y = [], True, y0
    while y <= y1:
        if up:
            out += ['G0 X%g Y%g' % (x0, y),
                    'G1 X%g Y%g E%g F%d' % (x1, y, e, f)]
