# =================== helpers: file builders ==================================
def _hdr():
    # NO '; R2-POSTPROC' tag, no LAYER_MARK - a REAL slicer source the
    # watcher has never seen before (otherwise process() skips it)
    return ['; generated by r190 fixture', 'M83', 'G90', 'G28',
            'G0 X50 Y50 F6000']


def _layer(z, types_moves):
    """types_moves: list of (type_comment_or_None, [gcode lines])"""
    out = [';LAYER_CHANGE', 'G1 Z%.2f F600' % z]
    for ty, lines in types_moves:
        if ty:
            out.append(';TYPE:%s' % ty)
        out += lines
    return out


def _square(x0, y0, x1, y1, e=1.0, f=1800):
    return ['G0 X%d Y%d' % (x0, y0),
            'G1 X%d Y%d E%g F%d' % (x1, y0, e, f),
            'G1 X%d Y%d E%g' % (x1, y1, e),
            'G1 X%d Y%d E%g' % (x0, y1, e),
            'G1 X%d Y%d E%g' % (x0, y0, e)]


def _hatch(x0, y0, x1, y1, step, e=0.5, f=2700):
    """parallel zigzag lines between y0..y1"""
    out = []
    up = True
    y = y0
    while y <= y1:
        if up:
            out.append('G0 X%d Y%d' % (x0, y))
            out.append('G1 X%d Y%d E%g F%d' % (x1, y, e, f))
        else:
            out.append('G0 X%d Y%d' % (x1, y))
            out.append('G1 X%d Y%d E%g F%d' % (x0, y, e, f))
        up = not up
        y += step
    return out


def _run(tmp, name, lines):
    p = os.path.join(tmp, name)
    open(p, 'w').write('\n'.join(lines) + '\n')
    summ = mod.process(p)
    txt = open(p).read()
    fi = [l for l in txt.split('\n') if l.startswith('_FILE_INFO')]
    return summ, txt, (fi[0] if fi else '')


